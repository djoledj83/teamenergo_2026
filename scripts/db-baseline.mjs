#!/usr/bin/env node
/**
 * Creates and applies the initial migration WITHOUT a shadow database.
 *
 * `prisma migrate dev` builds a throwaway shadow database to check that a
 * migration is reproducible, which needs the CREATEDB privilege. That is a
 * reasonable thing to withhold from an application role — especially in
 * production — so this does the same job the way Prisma documents for
 * baselining:
 *
 *   1. diff an empty database against the schema  (no database needed)
 *   2. write the SQL as a normal migration folder
 *   3. execute it against the target database
 *   4. record it as applied in _prisma_migrations
 *
 * The result is a real migration committed to the repo, identical to what
 * `migrate dev` would have produced. From here on `prisma migrate deploy`
 * works normally and never needs CREATEDB.
 *
 *   node scripts/db-baseline.mjs [--name init]
 */
import { execFileSync } from 'node:child_process';
import { mkdirSync, writeFileSync, existsSync, readdirSync } from 'node:fs';
import { join, resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const schemaPath = join(root, 'apps', 'api', 'prisma', 'schema.prisma');
const migrationsDir = join(root, 'apps', 'api', 'prisma', 'migrations');

const nameFlagIndex = process.argv.indexOf('--name');
const migrationName = nameFlagIndex !== -1 ? process.argv[nameFlagIndex + 1] : 'init';

/** shell:true joins args without quoting, so any path may contain spaces. */
const q = (value) => (/[\s]/.test(value) ? `"${value}"` : value);

function run(args, { capture = false } = {}) {
  // shell: true so this resolves npx.cmd on Windows.
  return execFileSync('npx', ['prisma', ...args.map(q)], {
    cwd: root,
    shell: true,
    encoding: 'utf8',
    stdio: capture ? ['ignore', 'pipe', 'inherit'] : 'inherit',
    maxBuffer: 32 * 1024 * 1024,
  });
}

if (!process.env.DATABASE_URL) {
  console.error('DATABASE_URL is not set. Run this through: npm run db:baseline');
  process.exit(1);
}

const existingMigrations = existsSync(migrationsDir)
  ? readdirSync(migrationsDir).filter((entry) => entry !== 'migration_lock.toml')
  : [];

// Allow a retry after a failed apply: a folder exists but nothing was
// recorded as applied, so reusing it is correct rather than an error.
const alreadyApplied = existingMigrations.length > 0 && process.env.FORCE_NEW !== '1';
if (alreadyApplied) {
  const folderName = existingMigrations.sort().at(-1);
  const file = join(migrationsDir, folderName, 'migration.sql');
  console.info(`Reusing the migration generated earlier: ${folderName}`);
  console.info('2/4  Applying it to the database…');
  try {
    run(['db', 'execute', '--file', file, '--schema', schemaPath]);
  } catch {
    console.error(
      '\nApplying the migration failed — see scripts/sql/grant-privileges.sql.\n' +
        'If the tables already exist, skip straight to: npm run db:seed\n',
    );
    process.exit(1);
  }
  console.info('3/4  Recording it as applied…');
  run(['migrate', 'resolve', '--applied', folderName, '--schema', schemaPath]);
  console.info('4/4  Regenerating the client…');
  run(['generate', '--schema', schemaPath]);
  console.info(`\nDone. Migration ${folderName} applied.\nNext: npm run db:seed`);
  process.exit(0);
}

console.info('1/4  Generating SQL from the schema…');
const sql = run(
  ['migrate', 'diff', '--from-empty', '--to-schema-datamodel', schemaPath, '--script'],
  { capture: true },
);

if (!sql.trim()) {
  console.error('Prisma produced no SQL — is the schema empty?');
  process.exit(1);
}

// Prisma orders migrations by folder name, so the timestamp prefix matters.
const stamp = new Date().toISOString().replace(/\D/g, '').slice(0, 14);
const folderName = `${stamp}_${migrationName}`;
const folder = join(migrationsDir, folderName);

mkdirSync(folder, { recursive: true });
writeFileSync(join(folder, 'migration.sql'), sql, 'utf8');
writeFileSync(
  join(migrationsDir, 'migration_lock.toml'),
  '# Please do not edit this file manually\nprovider = "postgresql"\n',
  'utf8',
);

const tableCount = (sql.match(/CREATE TABLE/g) ?? []).length;
console.info(`     wrote ${folderName}/migration.sql (${tableCount} tables)`);

console.info('2/4  Applying it to the database…');
try {
  run(['db', 'execute', '--file', join(folder, 'migration.sql'), '--schema', schemaPath]);
} catch {
  // Far and away the most common cause: the application role cannot create
  // objects in the database. Postgres checks the CREATE privilege before it
  // evaluates `CREATE SCHEMA IF NOT EXISTS`, so this fails on line 2 even
  // though the public schema already exists.
  console.error(
    '\nApplying the migration failed.\n\n' +
      'If the message mentions "permission denied for database" or\n' +
      '"permission denied for schema public", the role in DATABASE_URL cannot\n' +
      'create objects. Fix it once as a superuser:\n\n' +
      '  npx prisma db execute \\\n' +
      '    --url "postgresql://postgres:PASSWORD@localhost:5432/YOUR_DB" \\\n' +
      '    --file scripts/sql/grant-privileges.sql\n\n' +
      'Edit that file first if your role or database is not named\n' +
      'teamAdmin / teamenergo. Then run `npm run db:baseline` again — the\n' +
      'generated migration folder is reused, nothing is lost.\n',
  );
  process.exit(1);
}

console.info('3/4  Recording it as applied…');
run(['migrate', 'resolve', '--applied', folderName, '--schema', schemaPath]);

console.info('4/4  Regenerating the client…');
run(['generate', '--schema', schemaPath]);

console.info(`\nDone. Baseline migration ${folderName} created and applied.`);
console.info('Next: npm run db:seed');
